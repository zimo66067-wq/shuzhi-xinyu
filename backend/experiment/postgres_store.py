"""PostgreSQL/Neon experimental evidence store.

Keeps the SQLite Store contract (query placeholders, named/positional row
access, transaction boundary, hash chain), but NEVER stores the DSN on disk or
in returned JSON. A single transaction advisory lock deliberately serializes
writes, preserving the original BEGIN IMMEDIATE semantics for small cohorts.
"""
from contextlib import contextmanager
import time
import psycopg
from .store import Store

SCHEMA = """
CREATE TABLE IF NOT EXISTS experiment_meta (
  key TEXT PRIMARY KEY, value TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS users (
 id TEXT PRIMARY KEY, username TEXT UNIQUE NOT NULL, password_hash TEXT NOT NULL,
 role TEXT NOT NULL CHECK(role IN ('admin','executor')), enabled INTEGER NOT NULL DEFAULT 1
);
CREATE TABLE IF NOT EXISTS auth (
 token_hash TEXT PRIMARY KEY, user_id TEXT NOT NULL REFERENCES users(id),
 created DOUBLE PRECISION NOT NULL, expires DOUBLE PRECISION NOT NULL, fingerprint TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS batches (
 id TEXT PRIMARY KEY, name TEXT NOT NULL,
 kind TEXT NOT NULL CHECK(kind IN ('formal','pilot','automated')),
 state TEXT NOT NULL DEFAULT 'draft', config TEXT NOT NULL, config_hash TEXT NOT NULL,
 confirmed INTEGER NOT NULL DEFAULT 0, created DOUBLE PRECISION NOT NULL
);
CREATE TABLE IF NOT EXISTS cases (
 id TEXT PRIMARY KEY, batch_id TEXT NOT NULL REFERENCES batches(id), code TEXT NOT NULL,
 category TEXT NOT NULL, payload TEXT NOT NULL, UNIQUE(batch_id,code)
);
CREATE TABLE IF NOT EXISTS sessions (
 id TEXT PRIMARY KEY, batch_id TEXT NOT NULL REFERENCES batches(id),
 case_id TEXT NOT NULL REFERENCES cases(id), executor_id TEXT NOT NULL REFERENCES users(id),
 state TEXT NOT NULL DEFAULT 'assigned', turn_no INTEGER NOT NULL DEFAULT 0,
 admitted_until DOUBLE PRECISION, profile TEXT NOT NULL, raters TEXT NOT NULL,
 UNIQUE(batch_id,case_id)
);
CREATE TABLE IF NOT EXISTS nonces (
 token_hash TEXT PRIMARY KEY, session_id TEXT NOT NULL REFERENCES sessions(id),
 user_id TEXT NOT NULL, turn_no INTEGER NOT NULL, scope TEXT NOT NULL,
 issued DOUBLE PRECISION NOT NULL, expires DOUBLE PRECISION NOT NULL, consumed_by TEXT
);
CREATE TABLE IF NOT EXISTS turns (
 id TEXT PRIMARY KEY, request_id TEXT UNIQUE NOT NULL, trace_id TEXT UNIQUE NOT NULL,
 batch_id TEXT NOT NULL REFERENCES batches(id), session_id TEXT NOT NULL REFERENCES sessions(id),
 executor_id TEXT NOT NULL, turn_no INTEGER NOT NULL, body_hash TEXT NOT NULL,
 input TEXT NOT NULL, status TEXT NOT NULL, source TEXT, model_called INTEGER, output TEXT,
 attempts TEXT, created DOUBLE PRECISION NOT NULL, completed DOUBLE PRECISION,
 elapsed_ms DOUBLE PRECISION, response_modified INTEGER,
 UNIQUE(session_id, turn_no)
);
CREATE UNIQUE INDEX IF NOT EXISTS one_running_turn ON turns(session_id)
 WHERE status='running';
CREATE TABLE IF NOT EXISTS events (
 seq BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, id TEXT UNIQUE NOT NULL,
 batch_id TEXT, session_id TEXT, turn_id TEXT, actor_id TEXT NOT NULL,
 kind TEXT NOT NULL, utc_time DOUBLE PRECISION NOT NULL, data TEXT NOT NULL,
 prev_hash TEXT NOT NULL, hash TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS observations (
 id TEXT PRIMARY KEY, session_id TEXT NOT NULL REFERENCES sessions(id),
 actor_id TEXT NOT NULL, created DOUBLE PRECISION NOT NULL, payload TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS ratings (
 id TEXT PRIMARY KEY, session_id TEXT NOT NULL REFERENCES sessions(id),
 rater_id TEXT NOT NULL REFERENCES users(id), created DOUBLE PRECISION NOT NULL,
 payload TEXT NOT NULL, UNIQUE(session_id,rater_id)
);
CREATE TABLE IF NOT EXISTS decisions (
 id TEXT PRIMARY KEY, session_id TEXT NOT NULL REFERENCES sessions(id),
 actor_id TEXT NOT NULL, created DOUBLE PRECISION NOT NULL, payload TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS limits (
 id TEXT PRIMARY KEY, started DOUBLE PRECISION NOT NULL, count INTEGER NOT NULL
);
CREATE OR REPLACE FUNCTION experiment_raise_immutable() RETURNS trigger
LANGUAGE plpgsql AS $trigger$
BEGIN
 RAISE EXCEPTION 'append only evidence' USING ERRCODE='23514';
END;
$trigger$;
CREATE OR REPLACE FUNCTION experiment_check_turn_mutation() RETURNS trigger
LANGUAGE plpgsql AS $trigger$
BEGIN
 IF OLD.status <> 'running' THEN
   RAISE EXCEPTION 'completed turn immutable' USING ERRCODE='23514';
 END IF;
 RETURN NEW;
END;
$trigger$;
"""
# Fixed global lock for the one experiment database. The 40-session research
# workload is intentionally serial: audit-chain head, nonces, rate limits,
# sequence allocation, scoring and user/admin actions must be atomic together.
WRITE_LOCK = 4172102601
INIT_LOCK = 4172102602
IMMUTABLE_TABLES = ('events', 'observations', 'ratings', 'decisions', 'cases')


class CompatRow(dict):
    """Named-key and SQLite-compatible positional integer-key access."""
    def __getitem__(self, key):
        if isinstance(key, int):
            return list(self.values())[key]
        return super().__getitem__(key)


def compat_row_factory(cursor):
    names = [col.name for col in cursor.description]
    def make_row(values):
        return CompatRow(zip(names, values))
    return make_row


class CompatConnection:
    def __init__(self, connection):
        self.raw = connection

    def execute(self, sql, parameters=()):
        # Application's existing SQL has ? placeholders, not JSON operators.
        cursor = self.raw.cursor(row_factory=compat_row_factory)
        cursor.execute(sql.replace('?', '%s'), parameters)
        return cursor

    def commit(self):
        self.raw.commit()

    def rollback(self):
        self.raw.rollback()

    def close(self):
        self.raw.close()


class PostgresStore(Store):
    backend = 'postgres'

    def __init__(self, dsn):
        if not (dsn.startswith('postgresql://') or dsn.startswith('postgres://')):
            raise ValueError('A PostgreSQL DSN is required for Neon store')
        self._dsn = dsn
        # Never place credentials in self.path; this is read by a few
        # legacy SQLite-only formal/CLI code paths.
        self.path = 'postgresql-neon-experiment'
        db = self.connect()
        try:
            db.execute('SELECT pg_advisory_xact_lock(%s)', (INIT_LOCK,))
            # Send DDL in one PostgreSQL command. psycopg prepares
            # only statements with bound params; this has no params.
            db.raw.execute(SCHEMA)
            db.execute("""INSERT INTO experiment_meta(key,value) VALUES('schema_version','1')
                ON CONFLICT(key) DO NOTHING""")
            ver = db.execute("SELECT value FROM experiment_meta WHERE key='schema_version'").fetchone()[0]
            if ver != '1':
                raise ValueError('Unsupported newer PostgreSQL experiment schema')
            for table in IMMUTABLE_TABLES:
                for action in ('UPDATE', 'DELETE'):
                    trigger = f'immutable_{table}_{action.lower()}'
                    db.raw.execute(f"""DO $do$
BEGIN
 IF NOT EXISTS (SELECT 1 FROM pg_trigger
WHERE tgname='{trigger}' AND tgrelid='{table}'::regclass) THEN
  CREATE TRIGGER {trigger} BEFORE {action} ON {table}
   FOR EACH ROW EXECUTE FUNCTION experiment_raise_immutable();
 END IF;
END
$do$""")
            db.raw.execute("""DO $do$
BEGIN
 IF NOT EXISTS (SELECT 1 FROM pg_trigger
WHERE tgname='completed_turn_immutable' AND tgrelid='turns'::regclass) THEN
  CREATE TRIGGER completed_turn_immutable BEFORE UPDATE ON turns
   FOR EACH ROW EXECUTE FUNCTION experiment_check_turn_mutation();
 END IF;
 IF NOT EXISTS (SELECT 1 FROM pg_trigger
WHERE tgname='turn_no_delete' AND tgrelid='turns'::regclass) THEN
  CREATE TRIGGER turn_no_delete BEFORE DELETE ON turns
   FOR EACH ROW EXECUTE FUNCTION experiment_raise_immutable();
 END IF;
END
$do$""")
            db.commit()
        except BaseException:
            db.rollback()
            raise
        finally:
            db.close()

    def connect(self):
        # Neon pooler may close idle sessions: open a bounded connection for
        # each operation. Do not maintain unbounded connection pools in Functions.
        raw = psycopg.connect(self._dsn, connect_timeout=10,
                              application_name='xinyu_experiment')
        return CompatConnection(raw)

    @contextmanager
    def tx(self, read=False):
        db = self.connect()
        try:
            if not read:
                # PostgreSQL transaction-scoped lock replaces SQLite
                # BEGIN IMMEDIATE, serializing nonce consumption and hash log.
                db.execute('SELECT pg_advisory_xact_lock(%s)', (WRITE_LOCK,))
            yield db
            db.commit()
        except BaseException:
            db.rollback()
            raise
        finally:
            db.close()

    def rate(self, db, identity, maximum, seconds):
        now = time.time()
        row = db.execute('SELECT * FROM limits WHERE id=?', (identity,)).fetchone()
        if not row or now - row['started'] >= seconds:
            db.execute("""INSERT INTO limits(id,started,count) VALUES(?,?,1)
                  ON CONFLICT(id) DO UPDATE SET started=EXCLUDED.started,count=1""",
                       (identity, now))
            return True
        if row['count'] >= maximum:
            return False
        db.execute('UPDATE limits SET count=count+1 WHERE id=?', (identity,))
        return True
