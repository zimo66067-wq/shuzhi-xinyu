"""PostgreSQL storage for the isolated research experiment.

Provides the tiny SQLite-compatible interface used by the existing Workflow.
Use a dedicated PostgreSQL database; no data are imported from SQLite.
Every write transaction takes a transaction-scoped advisory lock to serialize
the globally chained audit log, nonces, reservations and rate limits across
serverless workers. This trades throughput for audit consistency.
"""
from contextlib import contextmanager
import re
import time

from .store import Store as SQLiteStore, SCHEMA as SQLITE_SCHEMA


class IndexedRow(dict):
    """Support both row['name'] and sqlite3-style row[0] without key ambiguity."""
    def __getitem__(self, key):
        if isinstance(key, int):
            return list(self.values())[key]
        return super().__getitem__(key)


def indexed_row(cursor):
    columns = [item.name for item in cursor.description]
    def make(values):
        return IndexedRow(zip(columns, values))
    return make


class Connection:
    def __init__(self, connection):
        self._conn = connection

    def execute(self, query, params=()):
        # The existing experiment SQL uses SQLite positional placeholders only.
        # Don't apply string substitutions to user-provided values.
        query = query.replace('?', '%s')
        return self._conn.execute(query, params)

    def commit(self):
        return self._conn.commit()

    def rollback(self):
        return self._conn.rollback()

    def close(self):
        return self._conn.close()


class PgStore(SQLiteStore):
    is_postgres = True
    # A stable namespace used by this project's global hash chain.
    AUDIT_LOCK_ID = 721479120403

    def __init__(self, connection_url):
        if not isinstance(connection_url, str) or not connection_url.startswith(
            ('postgresql://', 'postgres://')
        ):
            raise ValueError('EXPERIMENT_DATABASE_URL must be PostgreSQL URI')
        self.path = None
        self._connection_url = connection_url
        # Fail closed if the database is unreachable or schema creation fails.
        with self.tx() as db:
            schema = re.sub(r'\bREAL\b', 'DOUBLE PRECISION', SQLITE_SCHEMA)
            schema = schema.replace(
                'seq INTEGER PRIMARY KEY AUTOINCREMENT',
                'seq BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY'
            )
            for command in schema.split(';'):
                if command.strip():
                    db.execute(command)
            db.execute("""
                CREATE OR REPLACE FUNCTION xinyu_append_only_guard()
                RETURNS trigger LANGUAGE plpgsql AS $$
                BEGIN
                  RAISE EXCEPTION 'append only';
                END;
                $$
            """)
            for table in ('events', 'observations', 'ratings', 'decisions', 'cases'):
                for operation in ('UPDATE', 'DELETE'):
                    name = 'xinyu_immutable_' + table + '_' + operation.lower()
                    db.execute(f'DROP TRIGGER IF EXISTS {name} ON {table}')
                    db.execute(f'''
                        CREATE TRIGGER {name} BEFORE {operation}
                        ON {table} FOR EACH ROW
                        EXECUTE FUNCTION xinyu_append_only_guard()
                    ''')
            db.execute("""
                CREATE OR REPLACE FUNCTION xinyu_completed_turn_guard()
                RETURNS trigger LANGUAGE plpgsql AS $$
                BEGIN
                  RAISE EXCEPTION 'completed turn immutable';
                END;
                $$
            """)
            db.execute('DROP TRIGGER IF EXISTS xinyu_complete_turn_immutable ON turns')
            db.execute("""
                CREATE TRIGGER xinyu_complete_turn_immutable BEFORE UPDATE
                ON turns FOR EACH ROW WHEN (OLD.status <> 'running')
                EXECUTE FUNCTION xinyu_completed_turn_guard()
            """)
            db.execute('DROP TRIGGER IF EXISTS xinyu_turn_no_delete ON turns')
            db.execute("""
                CREATE TRIGGER xinyu_turn_no_delete BEFORE DELETE
                ON turns FOR EACH ROW EXECUTE FUNCTION xinyu_append_only_guard()
            """)
            db.execute("""
                CREATE TABLE IF NOT EXISTS xinyu_experiment_meta (
                    key TEXT PRIMARY KEY,
                    value TEXT NOT NULL
                )
            """)
            db.execute("""
                INSERT INTO xinyu_experiment_meta(key, value)
                VALUES ('schema_version', '1') ON CONFLICT(key) DO NOTHING
            """)
            version = db.execute(
                "SELECT value FROM xinyu_experiment_meta WHERE key='schema_version'"
            ).fetchone()['value']
            if version != '1':
                raise ValueError('unsupported experiment Postgres schema; refusing writes')

    def connect(self):
        try:
            import psycopg
        except ImportError as exc:
            raise RuntimeError('psycopg is required for Neon PostgreSQL') from exc
        conn = psycopg.connect(
            self._connection_url, connect_timeout=10,
            row_factory=indexed_row, autocommit=False
        )
        return Connection(conn)

    @contextmanager
    def tx(self, read=False):
        db = self.connect()
        try:
            if not read:
                # Only one writer of the global event hash chain at a time.
                # PostgreSQL releases this automatically at commit/rollback.
                db.execute('SELECT pg_advisory_xact_lock(%s)', (self.AUDIT_LOCK_ID,))
            yield db
            db.commit()
        except BaseException:
            db.rollback()
            raise
        finally:
            db.close()

    def rate(self, db, identity, maximum, seconds):
        now = time.time()
        row = db.execute('SELECT * FROM limits WHERE id=?', (identity,)).fetchone()
        if not row or now - row['started'] >= seconds:
            db.execute("""
                INSERT INTO limits(id, started, count)
                VALUES(?,?,1)
                ON CONFLICT(id)
                DO UPDATE SET started=EXCLUDED.started, count=1
            """, (identity, now))
            return True
        if row['count'] >= maximum:
            return False
        db.execute('UPDATE limits SET count=count+1 WHERE id=?', (identity,))
        return True

    def storage_probe(self):
        """Non-destructive connectivity/transactions probe; no formal records."""
        with self.tx(read=True) as db:
            result = db.execute("""
                SELECT current_database() AS database_name,
                       current_setting('server_version') AS server_version,
                       (SELECT value FROM xinyu_experiment_meta
                        WHERE key='schema_version') AS schema_version
            """).fetchone()
            return dict(result)
